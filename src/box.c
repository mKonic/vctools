#define HIDE_DEFAULT "special:vcbox"

const char *vc_box_display(const char *name) {
	return vc_state_get(name, "display");
}

const char *vc_box_signature(const char *name) {
	return vc_state_get(name, "signature");
}

int vc_box_alive(const char *name) {
	int pid = vc_state_get_int(name, "pid", 0);
	return pid > 0 && kill(pid, 0) == 0;
}

/* --- generated config --------------------------------------------------- */

// The box deliberately does NOT read the user's Hyprland config. Their window
// rules ("open Ladle on workspace 4 silent", fullscreen, render_unfocused) exist
// to hide an app inside the live session; in here the app should just fill the
// output. Since the app connects to the box's socket, host rules never see it.
static int write_config(struct vc_box_opts *o, const char *path) {
	FILE *f = fopen(path, "w");
	if (!f) return -1;

	fprintf(f, "# generated by vc — regenerated on every `vc box start`\n");
	// WAYLAND-1 is what the nested Wayland backend names its output; the name
	// has to match exactly or the rule is silently ignored and the output
	// inherits the host's fractional scale instead.
	fprintf(f, "monitor = WAYLAND-1, %dx%d@60, 0x0, %g\n\n", o->width, o->height, o->scale);

	fprintf(f,
	        "general {\n"
	        "    border_size = %d\n"
	        "    gaps_in = %d\n"
	        "    gaps_out = %d\n"
	        "}\n\n",
	        o->decorated ? 2 : 0, o->decorated ? 2 : 0, o->decorated ? 4 : 0);

	// Blocks must be multi-line: `blur { enabled = false }` on one line is a
	// parse error, which is where those red config warnings came from.
	fprintf(f,
	        "decoration {\n"
	        "    rounding = 0\n"
	        "    blur {\n"
	        "        enabled = false\n"
	        "    }\n"
	        "    shadow {\n"
	        "        enabled = false\n"
	        "    }\n"
	        "}\n\n");

	fprintf(f,
	        "animations {\n"
	        "    enabled = false\n"
	        "}\n\n");

	// render_unfocused_fps matters: the box window itself is unfocused on the
	// host, and without it the whole nested session would stop drawing.
	fprintf(f,
	        "misc {\n"
	        "    disable_hyprland_logo = true\n"
	        "    disable_splash_rendering = true\n"
	        "    force_default_wallpaper = 0\n"
	        "    disable_autoreload = true\n"
	        "    render_unfocused_fps = 60\n"
	        "}\n\n");

	fprintf(f,
	        "input {\n"
	        "    follow_mouse = 1\n"
	        "    kb_layout = us\n"
	        "}\n\n");

	if (!o->host_input) {
		// The nested Wayland backend mirrors the host's keyboard and pointer into
		// the box. That device carries stale modifier state (observed: Shift and
		// Super stuck down) which merges into every synthetic keystroke, so keys
		// arrive shifted and Return arrives as an escape sequence. Disabling the
		// mirrored devices is what makes synthetic input deterministic.
		fprintf(f,
		        "device {\n"
		        "    name = wl_keyboard\n"
		        "    enabled = false\n"
		        "}\n\n"
		        "device {\n"
		        "    name = wl_pointer\n"
		        "    enabled = false\n"
		        "}\n\n");
	}

	fprintf(f,
	        "ecosystem {\n"
	        "    no_update_news = true\n"
	        "    no_donation_nag = true\n"
	        "}\n\n"
	        "debug {\n"
	        "    disable_logs = false\n"
	        "}\n");

	fclose(f);
	return 0;
}

/* --- socket handover ---------------------------------------------------- */

// Hyprland accepts --socket only together with --wayland-fd, so vc creates the
// listening socket itself. That is what makes box names deterministic: the
// display is always vc-<name> instead of whichever wayland-N was free.
static int make_socket(const char *sockname) {
	char path[256];
	snprintf(path, sizeof path, "%s/%s", vc_runtime_dir(), sockname);

	struct sockaddr_un addr = { .sun_family = AF_UNIX };
	if (strlen(path) >= sizeof addr.sun_path) {
		vc_warn("socket path too long: %s", path);
		return -1;
	}
	snprintf(addr.sun_path, sizeof addr.sun_path, "%s", path);

	int fd = socket(AF_UNIX, SOCK_STREAM, 0);
	if (fd < 0) return -1;

	unlink(path); // a previous box that died without cleaning up
	if (bind(fd, (struct sockaddr *)&addr, sizeof addr) < 0) {
		vc_warn("bind %s: %s", path, strerror(errno));
		close(fd);
		return -1;
	}
	if (listen(fd, 128) < 0) {
		close(fd);
		return -1;
	}
	return fd;
}

/* --- host session ------------------------------------------------------- */

static int host_is_hyprland(void) {
	const char *sig = getenv("HYPRLAND_INSTANCE_SIGNATURE");
	return sig && *sig;
}

// Finds the instance signature Hyprland picked, by matching the socket name we
// handed it. `hyprctl instances` prints one block per instance.
static const char *find_signature(const char *sockname) {
	static char sig[256];
	const char *out = vc_capture("hyprctl instances 2>/dev/null");
	if (!out) return NULL;

	char cur[256] = { 0 };
	const char *p = out;
	while (*p) {
		const char *eol = strchr(p, '\n');
		size_t len = eol ? (size_t)(eol - p) : strlen(p);
		char line[512];
		snprintf(line, sizeof line > len + 1 ? len + 1 : sizeof line, "%s", p);

		if (!strncmp(line, "instance ", 9)) {
			snprintf(cur, sizeof cur, "%s", line + 9);
			char *colon = strrchr(cur, ':');
			if (colon) *colon = 0;
		} else {
			const char *ws = strstr(line, "wl socket:");
			if (ws) {
				ws += 10;
				while (*ws == ' ' || *ws == '\t') ws++;
				if (!strcmp(ws, sockname)) {
					snprintf(sig, sizeof sig, "%s", cur);
					return sig;
				}
			}
		}
		if (!eol) break;
		p = eol + 1;
	}
	return NULL;
}

// Parks the box's own window out of the way on the host and keeps it rendering.
static void hide_box_window(struct vc_box_opts *o, int pid) {
	if (!host_is_hyprland()) {
		vc_log("host is not Hyprland, leaving the box window where it is");
		return;
	}
	const char *hide = o->hide && *o->hide ? o->hide : HIDE_DEFAULT;

	// pid: selects the box window without needing to parse the client list, and
	// dispatching avoids mutating the user's config the way a window rule would.
	vc_run("hyprctl dispatch movetoworkspacesilent %s,pid:%d >/dev/null 2>&1", hide, pid);
	// Without render_unfocused a hidden window stops getting frame callbacks and
	// every capture returns the same stale frame.
	vc_run("hyprctl setprop pid:%d renderunfocused 1 >/dev/null 2>&1", pid);
}

// The nested output takes its size from the box window, so if the monitor rule
// did not get us the size we asked for, resize the window on the host instead.
static void force_size(struct vc_box_opts *o, int pid) {
	if (!host_is_hyprland()) return;
	vc_run("hyprctl dispatch setfloating pid:%d >/dev/null 2>&1", pid);
	vc_run("hyprctl dispatch resizewindowpixel exact %d %d,pid:%d >/dev/null 2>&1", o->width,
	       o->height, pid);
}

/* --- lifecycle ---------------------------------------------------------- */

static int wait_for_display(const char *display, double timeout_s) {
	struct vc_wl w;
	for (double waited = 0; waited < timeout_s; waited += 0.15) {
		if (vc_wl_connect(&w, display) == 0) {
			vc_wl_disconnect(&w);
			return 0;
		}
		vc_sleep_s(0.15);
	}
	return -1;
}

// Reports the size the box's output actually ended up with.
static int probe_size(const char *display, int *w_out, int *h_out) {
	struct vc_wl w;
	if (vc_wl_connect(&w, display) < 0) return -1;
	struct vc_output *o = vc_wl_output(&w, NULL);
	int rc = -1;
	if (o) {
		*w_out = o->logical_w;
		*h_out = o->logical_h;
		rc = 0;
	}
	vc_wl_disconnect(&w);
	return rc;
}

int vc_box_start(struct vc_box_opts *o) {
	if (vc_box_alive(o->name)) {
		vc_warn("box '%s' is already running", o->name);
		return 1;
	}

	const char *dir = vc_box_dir(o->name);
	if (vc_mkdirs(dir) < 0) vc_die("cannot create %s", dir);

	char conf[600], logpath[600], sockname[128];
	snprintf(conf, sizeof conf, "%s/hypr.conf", dir);
	snprintf(logpath, sizeof logpath, "%s/box.log", dir);
	snprintf(sockname, sizeof sockname, "vc-%s", o->name);

	if (write_config(o, conf) < 0) vc_die("cannot write %s", conf);

	// Catch config mistakes here rather than as a red banner inside the box.
	const char *verify = vc_capture("Hyprland --verify-config -c '%s' 2>&1 | tail -3", conf);
	if (verify && !strstr(verify, "config ok"))
		vc_warn("generated config did not verify clean:\n%s", verify);

	int sock = make_socket(sockname);
	if (sock < 0) return 1;

	pid_t pid = fork();
	if (pid < 0) vc_die("fork: %s", strerror(errno));

	if (pid == 0) {
		// Child: hand the listening socket over as fd 3.
		if (dup2(sock, 3) < 0) _exit(127);
		int flags = fcntl(3, F_GETFD);
		fcntl(3, F_SETFD, flags & ~FD_CLOEXEC);

		int log = open(logpath, O_WRONLY | O_CREAT | O_TRUNC, 0600);
		if (log >= 0) {
			dup2(log, STDOUT_FILENO);
			dup2(log, STDERR_FILENO);
		}
		setsid();

		unsetenv("HYPRLAND_INSTANCE_SIGNATURE"); // or it would talk to the host
		// Hyprland pushes its own WAYLAND_DISPLAY into systemd and dbus on
		// startup. That would rewrite the *user's* session environment, so every
		// app they launched afterwards would try to connect to the box. This is
		// the single most invasive thing a nested compositor can do; turn it off.
		setenv("HYPRLAND_NO_SD_VARS", "1", 1);
		setenv("HYPRLAND_NO_CRASHREPORTER", "1", 1);

		execlp("Hyprland", "Hyprland", "--socket", sockname, "--wayland-fd", "3", "-c", conf,
		       (char *)NULL);
		_exit(127);
	}

	close(sock);
	vc_state_set(o->name, "pid", vc_capture("echo %d", pid));
	vc_state_set(o->name, "display", sockname);
	vc_state_set(o->name, "config", conf);
	vc_state_set(o->name, "log", logpath);

	if (wait_for_display(sockname, 15.0) < 0) {
		vc_warn("box '%s' did not come up; see %s", o->name, logpath);
		kill(pid, SIGTERM);
		return 1;
	}

	const char *sig = find_signature(sockname);
	if (sig) vc_state_set(o->name, "signature", sig);

	hide_box_window(o, pid);

	int got_w = 0, got_h = 0;
	probe_size(sockname, &got_w, &got_h);
	if (got_w != o->width || got_h != o->height) {
		vc_log("output came up %dx%d, forcing %dx%d", got_w, got_h, o->width, o->height);
		force_size(o, pid);
		vc_sleep_s(0.6);
		probe_size(sockname, &got_w, &got_h);
	}

	char size[64];
	snprintf(size, sizeof size, "%dx%d", got_w, got_h);
	vc_state_set(o->name, "size", size);

	// XWayland inside the box gets its own DISPLAY; `vc box exec` must use that
	// one, never the host's, or X11 apps would open in the live session.
	const char *xdisp = vc_capture("grep -oE 'DISPLAY[ =:]+:[0-9]+' '%s' 2>/dev/null | grep -oE ':[0-9]+' | tail -1",
	                               logpath);
	if (xdisp && *xdisp) vc_state_set(o->name, "xdisplay", xdisp);

	printf("box %s up: WAYLAND_DISPLAY=%s %dx%d%s\n", o->name, sockname, got_w, got_h,
	       sig ? "" : " (no hyprctl signature)");
	if (got_w != o->width || got_h != o->height)
		vc_warn("requested %dx%d but got %dx%d", o->width, o->height, got_w, got_h);
	return 0;
}

int vc_box_kill(const char *name) {
	int pid = vc_state_get_int(name, "pid", 0);
	if (pid <= 0) {
		vc_warn("no box named '%s'", name);
		return 1;
	}
	if (kill(pid, SIGTERM) == 0) {
		for (int i = 0; i < 40 && kill(pid, 0) == 0; i++) vc_sleep_s(0.1);
		if (kill(pid, 0) == 0) kill(pid, SIGKILL);
	}

	const char *disp = vc_box_display(name);
	if (disp) {
		char path[512];
		snprintf(path, sizeof path, "%s/%s", vc_runtime_dir(), disp);
		unlink(path);
	}
	char statefile[600];
	snprintf(statefile, sizeof statefile, "%s/box", vc_box_dir(name));
	unlink(statefile);
	printf("box %s stopped\n", name);
	return 0;
}

int vc_box_list(void) {
	char root[512];
	snprintf(root, sizeof root, "%s/vctools", vc_runtime_dir());
	DIR *d = opendir(root);
	if (!d) return 0;

	struct dirent *e;
	while ((e = readdir(d))) {
		if (e->d_name[0] == '.') continue;
		const char *disp = vc_box_display(e->d_name);
		if (!disp) continue;
		const char *size = vc_state_get(e->d_name, "size");
		char sizebuf[64];
		snprintf(sizebuf, sizeof sizebuf, "%s", size ? size : "?");
		printf("%-16s %-14s %-10s %s\n", e->d_name, disp, sizebuf,
		       vc_box_alive(e->d_name) ? "running" : "dead");
	}
	closedir(d);
	return 0;
}

// Sets up the environment so a child process joins the box instead of the host.
static void apply_box_env(const char *name) {
	const char *disp = vc_box_display(name);
	if (!disp) vc_die("no box named '%s'", name);
	setenv("WAYLAND_DISPLAY", disp, 1);

	const char *sig = vc_box_signature(name);
	if (sig) setenv("HYPRLAND_INSTANCE_SIGNATURE", sig, 1);

	const char *xdisp = vc_state_get(name, "xdisplay");
	if (xdisp && *xdisp)
		setenv("DISPLAY", xdisp, 1);
	else
		unsetenv("DISPLAY"); // never leak the host's X server into the box
}

int vc_box_exec(const char *name, char **argv) {
	if (!vc_box_alive(name)) vc_die("box '%s' is not running", name);
	apply_box_env(name);
	execvp(argv[0], argv);
	vc_die("exec %s: %s", argv[0], strerror(errno));
	return 127;
}

int vc_box_env(const char *name) {
	const char *disp = vc_box_display(name);
	if (!disp) vc_die("no box named '%s'", name);
	printf("export WAYLAND_DISPLAY=%s\n", disp);
	const char *sig = vc_box_signature(name);
	if (sig) printf("export HYPRLAND_INSTANCE_SIGNATURE=%s\n", sig);
	const char *xdisp = vc_state_get(name, "xdisplay");
	if (xdisp && *xdisp) printf("export DISPLAY=%s\n", xdisp);
	else printf("unset DISPLAY\n");
	return 0;
}
